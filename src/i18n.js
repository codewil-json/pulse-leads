const languageOptions = [
  { code: 'pt', label: 'pt-BR', flag: '🇧🇷' },
  { code: 'en', label: 'EN', flag: '🇬🇧' },
  { code: 'es', label: 'ES', flag: '🇪🇸' },
  { code: 'fr', label: 'FR', flag: '🇫🇷' },
]

const getValue = (key) => {
  return key.split('.').reduce((acc, part) => (acc && acc[part] ? acc[part] : null), messages[state.locale]) || key
}

export function useI18n() {
  return {
    locale: readonly(state),
    t: getValue,
    setLocale: (value) => {
      state.locale = value
    },
    languageOptions,
  }
}
